    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        try {
        String nama = txtNama.getText();
        String biayaText = txtBiaya.getText();
        String jumlahText = txtJumlah.getText();

        double biaya = Double.parseDouble(biayaText);
        int jumlah = Integer.parseInt(jumlahText);

        double total = hitungTotal(biaya, jumlah);

        String kursus = cmbKursus.getSelectedItem().toString();

        txtHasil.setText(
            "HASIL PENDAFTARAN\n" +
            "========================\n" +
            "Nama   : " + nama + "\n" +
            "Kursus : " + kursus + "\n" +
            "Biaya  : " + biaya + "\n" +
            "Jumlah : " + jumlah + "\n" +
            "Total  : " + total
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Biaya dan jumlah harus berupa angka!",
            "Input Salah",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    } // TODO add your handling code here:
    }//GEN-LAST:event_btnProsesActionPerformed

